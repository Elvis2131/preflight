import { open, check, done, loadTemplate, mode } from "./lib.mjs";
const { page, close } = await open();
let legacyDialogs = 0;
page.on("dialog", () => legacyDialogs++);
check("clear is disabled for an empty design", await page.getByTestId("clear-architecture").isDisabled());
const options = await page.getByTestId("template-picker").locator("option").evaluateAll((items) => items.filter((item) => item.value).map((item) => ({ id: item.value, name: item.textContent })));
await loadTemplate(page, options[0].id);
await page.getByTestId("canvas-json-toggle").click();
const read = () => page.locator("pre").innerText();
const original = await read();
await page.getByTestId("template-picker").selectOption(options[1].id);
const popup = page.getByRole("dialog", { name: "Switch architecture sample?" });
await popup.waitFor();
check("sample switch uses an in-app popup naming the destination", (await popup.innerText()).includes(options[1].name) && legacyDialogs === 0);
check("opening the popup does not replace the design", await read() === original);
check("cancel receives keyboard focus", await popup.getByRole("button", { name: "Keep current design" }).evaluate((button) => button === document.activeElement));
await popup.getByRole("button", { name: "Keep current design" }).click();
check("cancelling preserves all nodes and connections", await read() === original);
await page.getByTestId("template-picker").selectOption(options[1].id);
await popup.waitFor();
await page.keyboard.press("Escape");
check("Escape keeps the current design", await popup.count() === 0 && await read() === original);
await page.getByTestId("template-picker").selectOption(options[1].id);
await popup.getByRole("button", { name: "Switch sample", exact: true }).click();
await page.waitForTimeout(1200);
check("proceed loads the requested architecture", (await page.getByTestId("loaded-template").innerText()).includes(options[1].name) && await read() !== original);
await page.getByTestId("clear-architecture").click();
const empty = JSON.parse(await read());
check("one click clears all services and connections", empty.nodes.length === 0 && empty.edges.length === 0);
check("clear removes the template context and disables itself", await page.getByTestId("loaded-template").count() === 0 && await page.getByTestId("clear-architecture").isDisabled());
await page.getByTestId("template-picker").selectOption(options[0].id);
await page.waitForTimeout(1200);
check("an empty design loads a sample directly", await popup.count() === 0 && JSON.parse(await read()).nodes.length > 0);
await mode(page, "simulate");
check("clear is unavailable in simulation", await page.getByTestId("clear-architecture").count() === 0);
await mode(page, "design");
await page.getByRole("button", { name: /dark mode/i }).click();
await page.getByTestId("template-picker").selectOption(options[1].id);
await popup.waitFor();
await page.screenshot({ path: "/tmp/preflight-template-confirmation-dark.png" });
check("popup follows dark mode", await page.locator("html").getAttribute("data-theme") === "dark");
await popup.getByRole("button", { name: "Keep current design" }).click();
await close();
done("16-clear-and-switch");
